#!/usr/bin/env python3
"""Compile HLSL shaders offline into C headers with SPIR-V, DXIL and MSL.

    python tools/compile_shaders.py                  # every engine/shaders/*.{vert,frag}.hlsl
    python tools/compile_shaders.py path/a.frag.hlsl # just these (output still goes to engine/shaders/compiled)

Each <name>.<stage>.hlsl becomes engine/shaders/compiled/<name>.<stage>.h holding one
`static const br_shader_blob br_shader_<name>_<stage>` (see engine/include/braty/br_gpu.h).

Pipeline per shader:
    HLSL --dxc -spirv--> SPIR-V --spirv-cross --msl--> MSL
    HLSL --dxc---------> DXIL
    SPIR-V --spirv-cross --reflect--> resource counts for SDL_GPUShaderCreateInfo

Resource conventions are SDL_GPU's (SDL_CreateGPUShader docs):
    vertex:   t[n]/s[n] in space0, b[n] in space1
    fragment: t[n]/s[n] in space2, b[n] in space3
Mark texture+sampler pairs [[vk::combinedImageSampler]] so SPIR-V gets combined samplers.

Tools: dxc and spirv-cross from PATH, $VULKAN_SDK/Bin, or the newest C:/VulkanSDK/*/Bin.
"""
import glob
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHADER_DIR = os.path.join(ROOT, "engine", "shaders")
OUT_DIR = os.path.join(SHADER_DIR, "compiled")

STAGES = {
    "vert": ("vs_6_0", "SDL_GPU_SHADERSTAGE_VERTEX"),
    "frag": ("ps_6_0", "SDL_GPU_SHADERSTAGE_FRAGMENT"),
}


def find_tool(name):
    found = shutil.which(name)
    if found:
        return found
    candidates = []
    if os.environ.get("VULKAN_SDK"):
        candidates.append(os.path.join(os.environ["VULKAN_SDK"], "Bin"))
        candidates.append(os.path.join(os.environ["VULKAN_SDK"], "bin"))
    candidates += sorted(glob.glob("C:/VulkanSDK/*/Bin"), reverse=True)
    for directory in candidates:
        for exe in (name + ".exe", name):
            path = os.path.join(directory, exe)
            if os.path.isfile(path):
                return path
    sys.exit("error: cannot find '%s' (install the Vulkan SDK or put it on PATH)" % name)


def run(cmd):
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        sys.stderr.write(result.stdout + result.stderr)
        sys.exit("error: command failed: %s" % " ".join(cmd))
    return result.stdout


def c_bytes(data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + " ".join("0x%02x," % b for b in data[i:i + 16]))
    return "\n".join(lines)


def compile_one(dxc, spirv_cross, src, tmp):
    base = os.path.basename(src)
    match = re.match(r"^([A-Za-z0-9_]+)\.(vert|frag)\.hlsl$", base)
    if not match:
        sys.exit("error: shader file must be named <name>.<vert|frag>.hlsl: %s" % src)
    name, stage = match.group(1), match.group(2)
    profile, sdl_stage = STAGES[stage]
    symbol = "br_shader_%s_%s" % (name, stage)

    spv = os.path.join(tmp, symbol + ".spv")
    dxil = os.path.join(tmp, symbol + ".dxil")
    msl = os.path.join(tmp, symbol + ".msl")
    run([dxc, "-spirv", "-fspv-target-env=vulkan1.0", "-T", profile, "-E", "main", "-Fo", spv, src])
    # vk:: attributes mean nothing to DXIL; silence that one warning there
    run([dxc, "-Wno-ignored-attributes", "-T", profile, "-E", "main", "-Fo", dxil, src])
    # spirv-cross renames entry point "main" to "main0" for MSL
    run([spirv_cross, spv, "--msl", "--msl-version", "20100", "--msl-decoration-binding", "--output", msl])
    reflect = json.loads(run([spirv_cross, spv, "--reflect"]))

    num_samplers = len(reflect.get("textures", [])) + len(reflect.get("separate_images", []))
    num_storage_textures = len(reflect.get("images", []))
    num_storage_buffers = len(reflect.get("ssbos", []))
    num_uniform_buffers = len(reflect.get("ubos", []))

    with open(spv, "rb") as f:
        spv_bytes = f.read()
    with open(dxil, "rb") as f:
        dxil_bytes = f.read()
    with open(msl, "rb") as f:
        msl_bytes = f.read()

    guard = "BR_SHADER_%s_%s_H" % (name.upper(), stage.upper())
    rel_src = os.path.relpath(src, ROOT).replace("\\", "/")
    text = """/* Generated by tools/compile_shaders.py from {src}. Do not edit. */
#ifndef {guard}
#define {guard}

#include "braty/br_gpu.h"

static const uint8_t {sym}_spirv[] = {{
{spirv}
}};

static const uint8_t {sym}_dxil[] = {{
{dxil}
}};

/* MSL source text (untested on this machine; see docs/BUILDING.md) */
static const uint8_t {sym}_msl[] = {{
{msl}
}};

static const br_shader_blob {sym} = {{
    "{name}.{stage}",
    {sdl_stage},
    {samplers}, /* samplers */
    {storage_textures}, /* storage textures */
    {storage_buffers}, /* storage buffers */
    {uniform_buffers}, /* uniform buffers */
    {{
        [BR_SHADER_FORMAT_SPIRV] = {{ {sym}_spirv, sizeof({sym}_spirv), "main" }},
        [BR_SHADER_FORMAT_DXIL] = {{ {sym}_dxil, sizeof({sym}_dxil), "main" }},
        [BR_SHADER_FORMAT_MSL] = {{ {sym}_msl, sizeof({sym}_msl), "main0" }},
    }},
}};

#endif
""".format(src=rel_src, guard=guard, sym=symbol, name=name, stage=stage, sdl_stage=sdl_stage,
           spirv=c_bytes(spv_bytes), dxil=c_bytes(dxil_bytes), msl=c_bytes(msl_bytes),
           samplers=num_samplers, storage_textures=num_storage_textures,
           storage_buffers=num_storage_buffers, uniform_buffers=num_uniform_buffers)

    out = os.path.join(OUT_DIR, "%s.%s.h" % (name, stage))
    with open(out, "w", newline="\n") as f:
        f.write(text)
    print("%s -> %s (spirv %d, dxil %d, msl %d bytes; samplers %d, uniforms %d)" % (
        rel_src, os.path.relpath(out, ROOT).replace("\\", "/"), len(spv_bytes), len(dxil_bytes),
        len(msl_bytes), num_samplers, num_uniform_buffers))


def main():
    sources = sys.argv[1:]
    if not sources:
        sources = sorted(glob.glob(os.path.join(SHADER_DIR, "*.vert.hlsl")) +
                         glob.glob(os.path.join(SHADER_DIR, "*.frag.hlsl")))
    if not sources:
        sys.exit("error: no shaders found in " + SHADER_DIR)
    dxc = find_tool("dxc")
    spirv_cross = find_tool("spirv-cross")
    os.makedirs(OUT_DIR, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        for src in sources:
            compile_one(dxc, spirv_cross, os.path.abspath(src), tmp)


if __name__ == "__main__":
    main()
