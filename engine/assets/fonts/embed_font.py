"""Turns the default font into a C byte array (stdlib only).

    python engine/assets/fonts/embed_font.py

Reads engine/assets/fonts/NotoSans-Regular.ttf (SIL OFL 1.1, see OFL.txt next to it) and
writes engine/src/text/br_font_default_data.c, so text works with no asset files.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
SOURCE = os.path.join(HERE, "NotoSans-Regular.ttf")
OUTPUT = os.path.join(ROOT, "engine", "src", "text", "br_font_default_data.c")


def main():
    with open(SOURCE, "rb") as f:
        data = f.read()
    lines = [
        "/* Generated by engine/assets/fonts/embed_font.py from NotoSans-Regular.ttf. Do not edit.",
        " * Noto Sans, Copyright 2022 The Noto Project Authors, SIL Open Font License 1.1",
        " * (engine/assets/fonts/OFL.txt). */",
        "#include <stddef.h>",
        "",
        "extern const unsigned char br_font_default_ttf[];",
        "extern const size_t br_font_default_ttf_size;",
        "",
        "const size_t br_font_default_ttf_size = %d;" % len(data),
        "const unsigned char br_font_default_ttf[] = {",
    ]
    for i in range(0, len(data), 24):
        lines.append(",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    with open(OUTPUT, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d bytes of font)" % (OUTPUT, len(data)))


if __name__ == "__main__":
    main()
