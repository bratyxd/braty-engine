/* br_websocket_frame.c - the socket-free half of websocket: the opening handshake (request,
 * accept key, the client checks of RFC 6455 section 4.1) and br_websocket_conn, wslay's event API
 * over in-memory bytes. wslay parses and writes frames, masks, reassembles fragments, answers
 * pings, validates the UTF-8 of text messages and close reasons, the reserved bits, opcodes, close
 * codes and the message limit, and runs the closing handshake. What it leaves to its caller is
 * here: a 1-byte close body, a close code for malformed frames (wslay sends an empty close), the
 * unread-bytes limit, the keep-alive, the close timeout and the states. */
#include "br_websocket_internal.h"

#include <SDL3/SDL.h>

/* wslay's configuration (generated by addons/websocket/CMakeLists.txt), then wslay. */
#include "config.h"
#include <wslay/wslay.h>

/* Bytes of a message's header in the unread queue: uint32 size + uint8 text. */
#define BR_WEBSOCKET_QUEUE_HEADER 5

/* ---- the opening handshake */

void br_websocket_key_text(const uint8_t random16[16], char out[BR_WEBSOCKET_KEY_LENGTH + 1])
{
    br_tls_base64_encode(random16, 16, out, BR_WEBSOCKET_KEY_LENGTH + 1);
}

void br_websocket_accept_key(const char *key, char out[BR_WEBSOCKET_ACCEPT_LENGTH + 1])
{
    char text[128];
    int length = SDL_snprintf(text, sizeof text, "%.64s%s", key, BR_WEBSOCKET_GUID);
    uint8_t digest[20];
    br_tls_sha1(text, (size_t)length, digest);
    br_tls_base64_encode(digest, sizeof digest, out, BR_WEBSOCKET_ACCEPT_LENGTH + 1);
}

static bool br_websocket_is_tchar(char c)
{
    return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') ||
           (c != '\0' && SDL_strchr("!#$%&'*+-.^_`|~", c) != NULL);
}

static bool br_websocket_is_space(char c)
{
    return c == ' ' || c == '\t';
}

/* The next comma-separated item of *list, without surrounding spaces: start and length. False
 * at the end. *list moves past the item and its comma. */
static bool br_websocket_next_item(const char **list, const char **start, size_t *length)
{
    const char *p = *list;
    if (*p == '\0') {
        return false;
    }
    const char *end = SDL_strchr(p, ',');
    const char *next = end != NULL ? end + 1 : p + SDL_strlen(p);
    if (end == NULL) {
        end = next;
    }
    while (p < end && br_websocket_is_space(*p)) {
        p++;
    }
    while (end > p && br_websocket_is_space(end[-1])) {
        end--;
    }
    *start = p;
    *length = (size_t)(end - p);
    *list = next;
    return true;
}

/* True when the comma-separated list has the item `token` (case-insensitive or exact). */
static bool br_websocket_list_has(const char *list, const char *token, bool ignore_case)
{
    size_t token_length = SDL_strlen(token);
    const char *start = NULL;
    size_t length = 0;
    while (br_websocket_next_item(&list, &start, &length)) {
        if (length == token_length && (ignore_case ? SDL_strncasecmp(start, token, length) == 0
                                                   : SDL_strncmp(start, token, length) == 0)) {
            return true;
        }
    }
    return false;
}

/* True when value, without surrounding spaces, is `word` (case-insensitive or exact). */
static bool br_websocket_value_is(const char *value, const char *word, bool ignore_case)
{
    while (br_websocket_is_space(*value)) {
        value++;
    }
    size_t length = SDL_strlen(value);
    while (length > 0 && br_websocket_is_space(value[length - 1])) {
        length--;
    }
    return length == SDL_strlen(word) &&
           (ignore_case ? SDL_strncasecmp(value, word, length) == 0 : SDL_strncmp(value, word, length) == 0);
}

bool br_websocket_protocols_valid(const char *protocols, char *error, size_t error_capacity)
{
    if (protocols == NULL) {
        return true;
    }
    const char *list = protocols;
    const char *start = NULL;
    size_t length = 0;
    bool any = false;
    while (br_websocket_next_item(&list, &start, &length)) {
        if (length == 0) {
            SDL_snprintf(error, error_capacity, "protocols '%.100s': an empty name", protocols);
            return false;
        }
        for (size_t i = 0; i < length; i++) {
            if (!br_websocket_is_tchar(start[i])) {
                SDL_snprintf(error, error_capacity, "protocols '%.100s': '%.*s' is not a token", protocols,
                             (int)(length < 64 ? length : 64), start);
                return false;
            }
        }
        any = true;
    }
    if (!any) {
        SDL_snprintf(error, error_capacity, "protocols is empty (pass NULL for none)");
        return false;
    }
    return true;
}

size_t br_websocket_write_handshake(char *out, size_t capacity, const br_http_url *url, const char *key,
                                    const char *protocols, const char *headers, char *error,
                                    size_t error_capacity)
{
    static const char *const ours[] = { "Upgrade", "Connection", "Sec-WebSocket-Key", "Sec-WebSocket-Version",
                                        "Sec-WebSocket-Protocol", "Sec-WebSocket-Extensions" };
    if (!br_http_headers_valid(headers, error, error_capacity) ||
        !br_websocket_protocols_valid(protocols, error, error_capacity)) {
        return 0;
    }
    for (size_t i = 0; i < BR_ARRAY_COUNT(ours); i++) {
        if (br_http_headers_has(headers, ours[i])) {
            SDL_snprintf(error, error_capacity, "headers name %s: websocket writes it (protocols go in the "
                         "protocols argument)", ours[i]);
            return 0;
        }
    }
    size_t size = 160 + SDL_strlen(key) + (protocols != NULL ? SDL_strlen(protocols) : 0) +
                  (headers != NULL ? SDL_strlen(headers) : 0);
    char *all = br_alloc(size);
    if (all == NULL) {
        SDL_snprintf(error, error_capacity, "out of memory");
        return 0;
    }
    SDL_snprintf(all, size, "Upgrade: websocket\r\nConnection: Upgrade\r\nSec-WebSocket-Key: %s\r\n"
                 "Sec-WebSocket-Version: 13\r\n%s%s%s%s", key,
                 protocols != NULL ? "Sec-WebSocket-Protocol: " : "", protocols != NULL ? protocols : "",
                 protocols != NULL ? "\r\n" : "", headers != NULL ? headers : "");
    size_t length = br_http_write_request(out, capacity, "GET", url, all, false, 0, error, error_capacity);
    br_free(all);
    return length;
}

bool br_websocket_handshake_check(const br_http_parser *p, const char *accept, const char *protocols,
                                  char *error, size_t error_capacity)
{
    int status = br_http_parser_status(p);
    if (status != 101) {
        SDL_snprintf(error, error_capacity, "the server answered %d instead of 101 Switching Protocols", status);
        return false;
    }
    bool upgrade = false;
    bool connection = false;
    int accepts = 0;
    bool accept_ok = false;
    int chosen_count = 0;
    const char *chosen = NULL;
    uint32_t count = br_http_parser_header_count(p);
    for (uint32_t i = 0; i < count; i++) {
        const char *name = NULL;
        const char *value = NULL;
        if (!br_http_parser_header_at(p, i, &name, &value)) {
            continue;
        }
        if (SDL_strcasecmp(name, "Upgrade") == 0) {
            if (!br_websocket_value_is(value, "websocket", true)) {
                SDL_snprintf(error, error_capacity, "handshake: Upgrade is '%.64s', not websocket", value);
                return false;
            }
            upgrade = true;
        } else if (SDL_strcasecmp(name, "Connection") == 0) {
            connection = connection || br_websocket_list_has(value, "Upgrade", true);
        } else if (SDL_strcasecmp(name, "Sec-WebSocket-Accept") == 0) {
            accepts++;
            accept_ok = br_websocket_value_is(value, accept, false);
        } else if (SDL_strcasecmp(name, "Sec-WebSocket-Extensions") == 0) {
            SDL_snprintf(error, error_capacity, "handshake: the server chose extensions we did not offer (%.64s)",
                         value);
            return false;
        } else if (SDL_strcasecmp(name, "Sec-WebSocket-Protocol") == 0) {
            chosen_count++;
            chosen = value;
        }
    }
    if (!upgrade) {
        SDL_snprintf(error, error_capacity, "handshake: no Upgrade: websocket in the 101 response");
        return false;
    }
    if (!connection) {
        SDL_snprintf(error, error_capacity, "handshake: no Connection: Upgrade in the 101 response");
        return false;
    }
    if (accepts != 1 || !accept_ok) {
        SDL_snprintf(error, error_capacity, "handshake: %s Sec-WebSocket-Accept (expected %s)",
                     accepts == 0 ? "no" : accepts > 1 ? "more than one" : "a wrong", accept);
        return false;
    }
    if (chosen_count > 1 || (chosen != NULL && SDL_strchr(chosen, ',') != NULL)) {
        SDL_snprintf(error, error_capacity, "handshake: the server chose more than one protocol");
        return false;
    }
    if (chosen != NULL) {
        char name[128];
        const char *list = chosen;
        const char *start = NULL;
        size_t length = 0;
        br_websocket_next_item(&list, &start, &length);
        SDL_snprintf(name, sizeof name, "%.*s", (int)(length < 127 ? length : 127), start);
        if (protocols == NULL || !br_websocket_list_has(protocols, name, false)) {
            SDL_snprintf(error, error_capacity, "handshake: the server chose protocol '%.64s', which we did not "
                         "offer", name);
            return false;
        }
    }
    return true;
}

bool br_websocket_utf8_valid(const void *data, size_t size)
{
    const uint8_t *s = data;
    size_t i = 0;
    while (i < size) {
        uint8_t b = s[i];
        if (b < 0x80) {
            i++;
            continue;
        }
        size_t more = 0;
        uint32_t code = 0;
        uint32_t least = 0;
        if ((b & 0xE0) == 0xC0) {
            more = 1;
            code = b & 0x1Fu;
            least = 0x80;
        } else if ((b & 0xF0) == 0xE0) {
            more = 2;
            code = b & 0x0Fu;
            least = 0x800;
        } else if ((b & 0xF8) == 0xF0) {
            more = 3;
            code = b & 0x07u;
            least = 0x10000;
        } else {
            return false;
        }
        if (size - i - 1 < more) {
            return false;
        }
        for (size_t k = 1; k <= more; k++) {
            uint8_t c = s[i + k];
            if ((c & 0xC0) != 0x80) {
                return false;
            }
            code = (code << 6) | (c & 0x3Fu);
        }
        if (code < least || code > 0x10FFFF || (code >= 0xD800 && code <= 0xDFFF)) {
            return false;
        }
        i += more + 1;
    }
    return true;
}

/* ---- buffers */

/* Room for `more` bytes at the end of a growing buffer. False when out of memory. */
static bool br_websocket_reserve(uint8_t **buffer, size_t *capacity, size_t used, size_t more)
{
    if (used + more <= *capacity) {
        return true;
    }
    size_t want = *capacity > 0 ? *capacity * 2 : 4096;
    while (want < used + more) {
        want *= 2;
    }
    uint8_t *grown = br_realloc(*buffer, want);
    if (grown == NULL) {
        return false;
    }
    *buffer = grown;
    *capacity = want;
    return true;
}

static void br_websocket_end_wslay(br_websocket_conn *c)
{
    wslay_event_shutdown_read(c->ctx);
    wslay_event_shutdown_write(c->ctx);
}

/* Fails the connection for a rule wslay does not check: our close frame, read stops. */
static void br_websocket_violation(br_websocket_conn *c, uint16_t code, const char *what)
{
    if (c->violation) {
        return;
    }
    c->violation = true;
    SDL_snprintf(c->error, sizeof c->error, "%s (closed with %u)", what, (unsigned)code);
    wslay_event_queue_close(c->ctx, code, NULL, 0);  /* refused when a close is already queued */
    wslay_event_shutdown_read(c->ctx);
}

/* ---- wslay callbacks */

static ssize_t br_websocket_recv_callback(wslay_event_context_ptr ctx, uint8_t *buf, size_t len, int flags,
                                          void *user)
{
    br_websocket_conn *c = user;
    (void)flags;
    if (c->in_size == 0) {
        /* nothing now (wslay stops reading), or the end of the stream (a failure for wslay) */
        wslay_event_set_error(ctx, c->eof ? WSLAY_ERR_CALLBACK_FAILURE : WSLAY_ERR_WOULDBLOCK);
        return -1;
    }
    size_t n = len < c->in_size ? len : c->in_size;
    SDL_memcpy(buf, c->in, n);
    c->in += n;
    c->in_size -= n;
    return (ssize_t)n;
}

static ssize_t br_websocket_send_callback(wslay_event_context_ptr ctx, const uint8_t *data, size_t len, int flags,
                                          void *user)
{
    br_websocket_conn *c = user;
    (void)flags;
    if (!br_websocket_reserve(&c->out, &c->out_capacity, c->out_size, len)) {
        c->out_of_memory = true;
        wslay_event_set_error(ctx, WSLAY_ERR_CALLBACK_FAILURE);
        return -1;
    }
    SDL_memcpy(c->out + c->out_size, data, len);
    c->out_size += len;
    return (ssize_t)len;
}

static int br_websocket_genmask_callback(wslay_event_context_ptr ctx, uint8_t *buf, size_t len, void *user)
{
    br_websocket_conn *c = user;
    (void)ctx;
    return c->random(c->random_user, buf, len) ? 0 : -1;
}

static void br_websocket_frame_start_callback(wslay_event_context_ptr ctx,
                                              const struct wslay_event_on_frame_recv_start_arg *arg, void *user)
{
    br_websocket_conn *c = user;
    (void)ctx;
    /* RFC 6455 section 5.5.1: a close body is empty or starts with a 2-byte code. wslay reads a
     * 1-byte body as "no code". */
    if (arg->opcode == WSLAY_CONNECTION_CLOSE && arg->payload_length == 1) {
        br_websocket_violation(c, WSLAY_CODE_PROTOCOL_ERROR, "protocol error: a close frame with a 1-byte body");
    }
}

/* Appends a received message to the unread queue. */
static void br_websocket_queue_push(br_websocket_conn *c, const uint8_t *data, size_t size, bool text)
{
    size_t need = BR_WEBSOCKET_QUEUE_HEADER + size + 1;
    if (c->queue_write - c->queue_read + need > BR_WEBSOCKET_MAX_UNREAD) {
        br_websocket_violation(c, WSLAY_CODE_POLICY_VIOLATION,
                               "unread messages over BR_WEBSOCKET_MAX_UNREAD (call br_websocket_receive every frame)");
        return;
    }
    if (c->queue_write + need > c->queue_capacity && c->queue_read > 0) {
        SDL_memmove(c->queue, c->queue + c->queue_read, c->queue_write - c->queue_read);
        c->queue_write -= c->queue_read;
        c->queue_read = 0;
    }
    if (!br_websocket_reserve(&c->queue, &c->queue_capacity, c->queue_write, need)) {
        c->out_of_memory = true;
        br_websocket_violation(c, WSLAY_CODE_INTERNAL_SERVER_ERROR, "out of memory for a received message");
        return;
    }
    uint32_t size32 = (uint32_t)size;
    uint8_t *p = c->queue + c->queue_write;
    SDL_memcpy(p, &size32, 4);
    p[4] = text ? 1 : 0;
    if (size > 0) {
        SDL_memcpy(p + BR_WEBSOCKET_QUEUE_HEADER, data, size);
    }
    p[BR_WEBSOCKET_QUEUE_HEADER + size] = '\0';
    c->queue_write += need;
}

static void br_websocket_msg_callback(wslay_event_context_ptr ctx, const struct wslay_event_on_msg_recv_arg *arg,
                                      void *user)
{
    br_websocket_conn *c = user;
    (void)ctx;
    if (arg->opcode == WSLAY_TEXT_FRAME || arg->opcode == WSLAY_BINARY_FRAME) {
        br_websocket_queue_push(c, arg->msg, arg->msg_length, arg->opcode == WSLAY_TEXT_FRAME);
    }
}

/* ---- the connection */

bool br_websocket_conn_init(br_websocket_conn *c, br_websocket_random_fn random, void *random_user, uint64_t now)
{
    SDL_zerop(c);
    struct wslay_event_callbacks callbacks;
    SDL_zero(callbacks);
    callbacks.recv_callback = br_websocket_recv_callback;
    callbacks.send_callback = br_websocket_send_callback;
    callbacks.genmask_callback = br_websocket_genmask_callback;
    callbacks.on_frame_recv_start_callback = br_websocket_frame_start_callback;
    callbacks.on_msg_recv_callback = br_websocket_msg_callback;
    /* ponytail: no extensions (no permessage-deflate): wslay's allowed RSV bits stay 0, so a
     * compressed frame is a protocol error. ponytail: wslay mallocs per received frame and per
     * queued message (libc, not br_alloc); wslay's no-buffering mode writing into our queue would
     * avoid the per-frame blocks. */
    wslay_event_context_ptr ctx = NULL;
    if (wslay_event_context_client_init(&ctx, &callbacks, c) != 0) {
        br_log_error("websocket: out of memory");
        return false;
    }
    c->ctx = ctx;
    c->random = random;
    c->random_user = random_user;
    c->state = BR_WEBSOCKET_OPEN;
    br_websocket_conn_set_max_message(c, 0);
    br_websocket_conn_set_times(c, (uint64_t)((double)BR_WEBSOCKET_DEFAULT_PING_INTERVAL * 1e9),
                                (uint64_t)((double)BR_WEBSOCKET_CLOSE_TIMEOUT * 1e9), now);
    return true;
}

void br_websocket_conn_free(br_websocket_conn *c)
{
    if (c->ctx != NULL) {
        wslay_event_context_free(c->ctx);
    }
    br_free(c->out);
    br_free(c->queue);
    br_free(c->current);
    SDL_zerop(c);
}

static bool br_websocket_terminal(const br_websocket_conn *c)
{
    return c->state == BR_WEBSOCKET_CLOSED || c->state == BR_WEBSOCKET_FAILED;
}

static void br_websocket_finish(br_websocket_conn *c, br_websocket_state state, uint16_t close_code)
{
    c->state = state;
    c->close_code = close_code;
    br_websocket_end_wslay(c);
}

/* Writes wslay's queued frames to the output and notes the close code we sent. */
static void br_websocket_flush(br_websocket_conn *c)
{
    if (wslay_event_send(c->ctx) != 0 && !c->out_of_memory) {
        c->out_of_memory = true;  /* the send callback fails only when the output cannot grow */
    }
    if (c->sent_code == 0 && wslay_event_get_close_sent(c->ctx)) {
        c->sent_code = wslay_event_get_status_code_sent(c->ctx);
    }
}

/* Our close frame 1002 for a malformed frame: wslay queued an empty close for it, which is not
 * sent; this one is (masked, as every client frame). */
static void br_websocket_malformed(br_websocket_conn *c)
{
    uint8_t mask[4] = { 0, 0, 0, 0 };
    c->random(c->random_user, mask, sizeof mask);
    uint8_t frame[8] = { 0x88, 0x82, mask[0], mask[1], mask[2], mask[3], (uint8_t)((1002 >> 8) ^ mask[0]),
                         (uint8_t)((1002 & 0xFF) ^ mask[1]) };
    wslay_event_shutdown_write(c->ctx);
    if (br_websocket_reserve(&c->out, &c->out_capacity, c->out_size, sizeof frame)) {
        SDL_memcpy(c->out + c->out_size, frame, sizeof frame);
        c->out_size += sizeof frame;
        c->sent_code = 1002;
    }
    SDL_snprintf(c->error, sizeof c->error, "protocol error: a malformed frame (a control frame over 125 bytes or "
                 "fragmented, a length not in its shortest form or over 2^63) (closed with 1002)");
}

/* After wslay ran: the state the connection is in now. recv_result: wslay_event_recv's. */
static void br_websocket_settle(br_websocket_conn *c, int recv_result)
{
    if (br_websocket_terminal(c)) {
        return;
    }
    if (recv_result == WSLAY_ERR_CALLBACK_FAILURE && !c->eof && !c->violation &&
        !wslay_event_get_close_received(c->ctx)) {
        br_websocket_malformed(c);
        br_websocket_finish(c, BR_WEBSOCKET_FAILED, 1006);
        return;
    }
    br_websocket_flush(c);
    if (c->out_of_memory && !c->violation) {
        SDL_snprintf(c->error, sizeof c->error, "out of memory");
        br_websocket_finish(c, BR_WEBSOCKET_FAILED, 1006);
        return;
    }
    if (c->violation) {
        br_websocket_finish(c, BR_WEBSOCKET_FAILED, 1006);
        return;
    }
    bool received = wslay_event_get_close_received(c->ctx) != 0;
    if (!wslay_event_get_read_enabled(c->ctx) && !received && !c->closed_by_us) {
        /* wslay found a protocol error and sent its close frame */
        uint16_t code = c->sent_code;
        if (code == WSLAY_CODE_INVALID_FRAME_PAYLOAD_DATA) {
            SDL_snprintf(c->error, sizeof c->error, "invalid UTF-8 in a text message or close reason (closed with 1007)");
        } else if (code == WSLAY_CODE_MESSAGE_TOO_BIG) {
            SDL_snprintf(c->error, sizeof c->error, "a message over the limit of %llu bytes (closed with 1009)",
                         (unsigned long long)c->max_message);
        } else {
            SDL_snprintf(c->error, sizeof c->error, "protocol error: reserved bits, an unknown opcode, a frame out of "
                         "order, a masked frame or an invalid close code (closed with %u)", (unsigned)code);
        }
        br_websocket_finish(c, BR_WEBSOCKET_FAILED, 1006);
        return;
    }
    if (received && wslay_event_get_close_sent(c->ctx)) {
        br_websocket_finish(c, BR_WEBSOCKET_CLOSED, wslay_event_get_status_code_received(c->ctx));
    }
}

void br_websocket_conn_feed(br_websocket_conn *c, const void *data, size_t size, uint64_t now)
{
    if (c->ctx == NULL || br_websocket_terminal(c) || size == 0) {
        return;
    }
    c->last_received = now;
    c->ping_waiting = false;
    c->in = data;
    c->in_size = size;
    int result = wslay_event_recv(c->ctx);
    c->in = NULL;
    c->in_size = 0;  /* wslay read everything, or stopped reading after a close */
    if (result == WSLAY_ERR_NOMEM) {
        c->out_of_memory = true;
    }
    br_websocket_settle(c, result);
}

void br_websocket_conn_end(br_websocket_conn *c, const char *reason, uint64_t now)
{
    (void)now;
    if (c->ctx == NULL || br_websocket_terminal(c)) {
        return;
    }
    c->eof = true;
    br_websocket_settle(c, 0);
    if (!br_websocket_terminal(c)) {
        SDL_snprintf(c->error, sizeof c->error, "%s",
                     reason != NULL && reason[0] != '\0' ? reason : "connection dropped without a close frame");
        br_websocket_finish(c, BR_WEBSOCKET_CLOSED, 1006);
    }
}

void br_websocket_conn_update(br_websocket_conn *c, uint64_t now)
{
    if (c->ctx == NULL || br_websocket_terminal(c)) {
        return;
    }
    if (c->state == BR_WEBSOCKET_OPEN && c->ping_interval > 0) {
        if (c->ping_waiting && now - c->ping_sent >= c->ping_interval) {
            SDL_snprintf(c->error, sizeof c->error, "keep-alive: nothing received for %.1f s (a ping went "
                         "unanswered): connection dropped", (double)c->ping_interval * 2e-9);
            br_websocket_finish(c, BR_WEBSOCKET_CLOSED, 1006);
            return;
        }
        if (!c->ping_waiting && now - c->last_received >= c->ping_interval) {
            struct wslay_event_msg ping = { WSLAY_PING, NULL, 0 };
            wslay_event_queue_msg(c->ctx, &ping);
            c->ping_waiting = true;
            c->ping_sent = now;
        }
    }
    if (c->state == BR_WEBSOCKET_CLOSING && now >= c->close_deadline) {
        SDL_snprintf(c->error, sizeof c->error, "no close reply within %.1f s", (double)c->close_timeout * 1e-9);
        br_websocket_finish(c, BR_WEBSOCKET_CLOSED, 1006);
        return;
    }
    br_websocket_settle(c, 0);
}

bool br_websocket_conn_send(br_websocket_conn *c, bool text, const void *data, size_t size)
{
    if (c->ctx == NULL || c->state != BR_WEBSOCKET_OPEN) {
        return false;
    }
    struct wslay_event_msg msg = { (uint8_t)(text ? WSLAY_TEXT_FRAME : WSLAY_BINARY_FRAME), data, size };
    bool ok = wslay_event_queue_msg(c->ctx, &msg) == 0;
    br_websocket_settle(c, 0);
    return ok && !br_websocket_terminal(c);
}

bool br_websocket_conn_close(br_websocket_conn *c, uint16_t code, const char *reason, uint64_t now)
{
    if (c->ctx == NULL || c->state != BR_WEBSOCKET_OPEN) {
        return false;
    }
    size_t length = reason != NULL ? SDL_strlen(reason) : 0;
    if (wslay_event_queue_close(c->ctx, code, (const uint8_t *)reason, length > 123 ? 123 : length) != 0) {
        return false;
    }
    c->closed_by_us = true;
    c->state = BR_WEBSOCKET_CLOSING;
    c->close_deadline = now + c->close_timeout;
    br_websocket_settle(c, 0);
    return true;
}

bool br_websocket_conn_receive(br_websocket_conn *c, br_websocket_message *out)
{
    if (c->queue_read == c->queue_write) {
        return false;
    }
    uint32_t size = 0;
    const uint8_t *p = c->queue + c->queue_read;
    SDL_memcpy(&size, p, 4);
    if (!br_websocket_reserve(&c->current, &c->current_capacity, 0, (size_t)size + 1)) {
        br_log_error("websocket: out of memory reading a message of %u bytes", (unsigned)size);
        return false;
    }
    SDL_memcpy(c->current, p + BR_WEBSOCKET_QUEUE_HEADER, (size_t)size + 1);
    out->data = c->current;
    out->size = size;
    out->text = p[4] != 0;
    c->queue_read += BR_WEBSOCKET_QUEUE_HEADER + (size_t)size + 1;
    if (c->queue_read == c->queue_write) {
        c->queue_read = 0;
        c->queue_write = 0;
    }
    return true;
}

void br_websocket_conn_set_max_message(br_websocket_conn *c, size_t bytes)
{
    size_t limit = BR_WEBSOCKET_MAX_UNREAD - BR_WEBSOCKET_QUEUE_HEADER - 1;
    c->max_message = bytes == 0 ? BR_WEBSOCKET_DEFAULT_MAX_MESSAGE : bytes > limit ? limit : bytes;
    if (c->ctx != NULL) {
        wslay_event_config_set_max_recv_msg_length(c->ctx, c->max_message);
    }
}

void br_websocket_conn_set_times(br_websocket_conn *c, uint64_t ping_interval, uint64_t close_timeout, uint64_t now)
{
    c->ping_interval = ping_interval;
    c->close_timeout = close_timeout;
    c->last_received = now;
    c->ping_waiting = false;
}

const void *br_websocket_conn_output(const br_websocket_conn *c, size_t *size)
{
    *size = c->out_size;
    return c->out_size > 0 ? c->out : NULL;
}

void br_websocket_conn_output_clear(br_websocket_conn *c)
{
    c->out_size = 0;
}
